// Bundle plain static family-game assets as text ESM for the dedicated Lab Worker.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('./cadets/',import.meta.url));
const files = [
  ['index.html','text/html; charset=utf-8'],
  ['style.css','text/css; charset=utf-8'],
  ['app.mjs','text/javascript; charset=utf-8'],
  ['rules.mjs','text/javascript; charset=utf-8']
];
const snapshot = Object.fromEntries(await Promise.all(files.map(async ([file,type]) => ['/projects/cadets/'+file,{body:await readFile(root+file,'utf8'),type}])));
await writeFile(fileURLToPath(new URL('./cadets-snapshot.mjs',import.meta.url)), '// Generated by node lab/build-cadets-snapshot.mjs. Edit lab/cadets/ files instead.\nexport const CADETS_FILES = '+JSON.stringify(snapshot)+';\n');
console.log('Cadets Worker snapshot built: '+Object.keys(snapshot).join(', '));
