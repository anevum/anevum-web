'    vec3 planetColor=surface*(.23+1.22*diffuse)+amber*city*.65;',
'    planetColor+=mix(u_tone,vec3(.54,.79,1.0),.53)*(atmosphere*.68+.08*land*diffuse);',
'    float cloud=noise2(norm.xy*32.0+norm.yz*5.0+vec2(t*.004,0.0));',
'    planetColor+=vec3(.30,.46,.64)*smoothstep(.7,.89,cloud)*diffuse*.13;',
'    color=mix(color,planetColor,clamp(u_shape.x,0.0,1.0));',
'  }',
'  // Analytic ring-plane intersection: real spatial parallax, no flat JPEG.',
'  vec3 axis=normalize(vec3(0.11,0.74,0.66));',
'  float denominator=dot(rd,axis);',
'  if(abs(denominator)>0.0001){',
'    float ringT=dot(center-ro,axis)/denominator;',
'    if(ringT>0.0){',
'      vec3 local=ro+rd*ringT-center;',
'      float rad=length(local);',
'      float ringRadius=2.06+u_density*0.16+u_pulse*0.055;',
'      float thin=abs(rad-ringRadius);',
'      float wide=abs(rad-(ringRadius+0.24));',
'      float energy=exp(-thin*55.0)*1.2+exp(-thin*6.0)*0.19+exp(-wide*72.0)*0.57;',
'      if(planetT<0.0||ringT<planetT){',
'        color+=u_shape.x*(u_tone*energy*(0.78+u_pulse*0.52)+vec3(0.21,0.30,0.48)*exp(-thin*120.0)*0.34);',
'      }',
'    }',
'  }',
'  // Three spatial disciplines live inside the same renderer: Commons',
'  // constellations, creator orbits and Studio fabrication instruments.',
'  // These are analytic graphics, not unverified activity indicators.',
'  vec2 hud=uv-vec2(.5,.03);',
'  float radius=length(hud);',
'  float angle=atan(hud.y,hud.x);',
'  float constellation=exp(-abs(radius-(.55+.042*sin(angle*5.0+t*.012)))*55.0);',
'  float starsArc=exp(-abs(sin(angle*10.0+t*.02))*19.0)*constellation;',
'  color+=mix(u_tone,amber,.4)*(constellation*.065+starsArc*.20)*commons;',
