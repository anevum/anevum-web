'vec3 boxNormal(vec3 p,vec3 center,vec3 extent){',
'  vec3 q=(p-center)/extent,a=abs(q);',
'  if(a.x>a.y&&a.x>a.z)return vec3(sign(q.x),0.0,0.0);',
'  if(a.y>a.z)return vec3(0.0,sign(q.y),0.0);',
'  return vec3(0.0,0.0,sign(q.z));',
