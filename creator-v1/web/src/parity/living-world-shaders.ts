'  float mist=noise2(uv*5.3-vec2(t*0.003,t*0.002));',
'  float zenith=smoothstep(-0.65,0.75,uv.y);',
'  vec3 base=mix(vec3(0.006,0.014,0.037),vec3(0.017,0.027,0.074),zenith);',
'  vec3 color=base+u_tone*(0.025+0.09*nebula*nebula);',
'  color+=u_tone*(0.085*pow(mist,3.0))*smoothstep(-0.8,1.2,uv.y);',
'  // The star field is deterministically generated, never simulated traffic.',
'  vec2 starUV=uv*vec2(81.0,59.0)+vec2(38.13,6.12);',
