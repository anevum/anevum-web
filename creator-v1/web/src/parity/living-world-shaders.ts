'  float creators=1.0-smoothstep(0.0,0.9,abs(u_architecture-2.0));',
'  float studio=1.0-smoothstep(0.0,0.9,abs(u_architecture-3.0));',
'  float worlds=1.0-smoothstep(0.0,0.9,abs(u_architecture-4.0));',
'  vec3 amber=vec3(0.98,0.62,0.31);',
'  // Perspective transit deck. Lines converge into the environment.',
'  float tf=(-1.37-ro.y)/min(-0.0002,rd.y);',
'  if(tf>0.0&&tf<85.0){',
'    vec3 gp=ro+rd*tf;',
'    vec2 cells=abs(fract(gp.xz*0.44)-0.5);',
'    float grid=(1.0-smoothstep(0.009,0.035,min(cells.x,cells.y)));',
'    float nearFade=1.0-smoothstep(7.0,37.0,tf);',
'    float lane=exp(-abs(length(gp.xz)-4.0)*1.7);',
'    color=mix(color,vec3(0.015,0.035,0.075),0.65*nearFade);',
'    color+=u_tone*(grid*0.13+lane*0.18)*nearFade;',
