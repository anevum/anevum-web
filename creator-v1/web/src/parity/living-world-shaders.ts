'  if(planetT>0.0){',
'    vec3 pos=ro+planetT*rd;vec3 norm=normalize(pos-center);',
'    vec3 sunlight=normalize(vec3(-0.56,0.68,-0.51));',
'    float direct=dot(norm,sunlight);',
'    float diffuse=max(0.0,direct);',
'    float atmosphere=pow(1.0-max(0.0,dot(norm,-rd)),3.2);',
'    float terrain=noise2(norm.xy*7.2+norm.yz*3.2+vec2(t*.002,0.0));',
'    float detail=noise2(norm.xy*24.0+norm.yz*8.0);',
'    float land=smoothstep(.41,.71,terrain*.81+detail*.19);',
'    vec3 ocean=mix(vec3(.018,.040,.104),vec3(.035,.093,.183),diffuse);',
'    vec3 continent=mix(vec3(.026,.078,.094),u_tone*.48+vec3(.018,.030,.045),diffuse);',
'    vec3 surface=mix(ocean,continent,land);',
'    float twilight=smoothstep(-.21,.61,direct);',
