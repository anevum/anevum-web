'float lineGlow(float d,float radius){return radius/(max(radius,d));}',
'vec3 surfaceGlow(vec3 col,float amt){return col*amt;}',
'// Analytic three-dimensional construction: no texture or expensive raymarch.',
'float boxHit(vec3 ro,vec3 rd,vec3 center,vec3 extent){',
