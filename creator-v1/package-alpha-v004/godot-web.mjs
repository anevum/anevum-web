/* ANEVUM V006 - advisory Godot web export inspection.
 * Never certifies code safety, device support or permission to publish.
 * Upload admission remains in the V004 authoritative ZIP/storage pipeline.
 */
import { ZIP_LIMITS } from "./archive.mjs";

const ROOT_WEB_FILE = /^[^/]+\.(?:wasm|pck|js)$/i;
function rootOfType(entries, extension) {
  return entries.filter(entry => ROOT_WEB_FILE.test(entry.path) &&
    entry.path.toLowerCase().endsWith(extension));
}
export function inspectGodotWebExport(entries, { archiveBytes = null } = {}) {
  const files = Array.isArray(entries) ? entries.filter(x => x && typeof x.path === "string") : [];
  const paths = new Set(files.map(x => x.path));
  const packFiles = rootOfType(files, ".pck");
  const wasmFiles = rootOfType(files, ".wasm");
  const loaderFiles = rootOfType(files, ".js");
  const projectSource = paths.has("project.godot");
  const godotLike = packFiles.length > 0 || projectSource;
  if (!godotLike) return null;

  const hasEntrypoint = paths.has("index.html");
  const exported = hasEntrypoint && packFiles.length > 0;
  const issues = [];
  const add = (code, severity, message, fix) => issues.push({ code, severity, message, fix });
  if (!hasEntrypoint) {
    add("AEP_GODOT_WEB_EXPORT_REQUIRED", "blocker",
      "Godot project data is not a playable web export.",
      "In Godot, export a Web preset with index.html, then ZIP the contents of that export directory.");
  }
  if (hasEntrypoint && !packFiles.length) {
    add("AEP_GODOT_PACK_MISSING", "blocker",
      "The Godot web asset pack is missing.",
      "Keep the exported .pck alongside index.html, the JavaScript loader, and the WebAssembly module.");
  }
  if (exported && !wasmFiles.length) {
    add("AEP_GODOT_WASM_MISSING", "blocker",
      "The Godot WebAssembly engine module is missing.",
      "Export for Web, and include the generated .wasm file at the archive root.");
  }
  if (exported && !loaderFiles.length) {
    add("AEP_GODOT_LOADER_MISSING", "blocker",
      "The Godot JavaScript boot loader is missing.",
      "Include the JavaScript file generated by the same Godot Web export.");
  }
  // V004 is deliberately a small pilot, not a general-purpose large-file uploader.
  const tooLarge = files.filter(x => Number.isSafeInteger(x.unpacked) &&
    x.unpacked > ZIP_LIMITS.singleFile);
  if (tooLarge.length) {
    add("AEP_GODOT_LARGE_FILE", "blocker",
      "This Godot build contains an asset larger than the current 12 MiB per-file pilot limit.",
      "Use the planned isolated large-build publication pipeline, or ship a reviewed native desktop edition. Do not split or rename engine files to evade limits.");
  }
  const expanded = files.reduce((sum, x) => sum +
    (Number.isSafeInteger(x.unpacked) && x.unpacked >= 0 ? x.unpacked : 0), 0);
  if (expanded > ZIP_LIMITS.inflated) {
    add("AEP_GODOT_EXPANDED_LIMIT", "blocker",
      "This Godot build exceeds the current 48 MiB expanded-build pilot limit.",
      "The dedicated large-build pipeline is required; the small ZIP uploader must remain bounded.");
  }
  if (archiveBytes !== null && archiveBytes > ZIP_LIMITS.archive) {
    add("AEP_GODOT_ARCHIVE_LIMIT", "blocker",
      "This Godot archive exceeds the current 20 MiB ZIP pilot limit.",
      "Use the future large-build path or a separately verified native release.");
  }
  if (projectSource && exported) {
    add("AEP_GODOT_SOURCE_IN_EXPORT", "warning",
      "A Godot source project file appears inside the browser export.",
      "Export only release assets; do not include editor cache, source secrets, or internal project files.");
  }
  if (exported) {
    add("AEP_GODOT_BROWSER_QA", "info",
      "Godot browser support still needs real-device testing.",
      "Target Godot 4 Compatibility/WebGL 2; prefer a single-threaded GDScript web export and test phone Safari, desktop browsers, and controller input. A viewport preview is not certification.");
  }
  return {
    engine: "godot",
    exportKind: exported ? "godot-web" : "godot-source",
    entrypoint: hasEntrypoint ? "index.html" : null,
    browserCandidate: exported && !issues.some(x => x.severity === "blocker"),
    needsLargeBuild: issues.some(x => ["AEP_GODOT_LARGE_FILE","AEP_GODOT_EXPANDED_LIMIT","AEP_GODOT_ARCHIVE_LIMIT"].includes(x.code)),
    assets: { wasm: wasmFiles.length, pack: packFiles.length, loader: loaderFiles.length, expandedBytes: expanded },
    issues
  };
}
